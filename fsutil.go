package main

import (
	"os"
	"path/filepath"
)

// writeFileAtomic écrit data dans path sans jamais laisser de fichier à moitié
// écrit : fichier temporaire, fsync, renommage, puis fsync du dossier. Après une
// coupure de courant, on retrouve soit l'ancienne version, soit la nouvelle.
func writeFileAtomic(path string, data []byte, perm os.FileMode) error {
	tmp := path + ".tmp"
	f, err := os.OpenFile(tmp, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, perm)
	if err != nil {
		return err
	}
	_, err = f.Write(data)
	if err == nil {
		err = f.Sync()
	}
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		_ = os.Remove(tmp)
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	syncDir(filepath.Dir(path))
	return nil
}

// syncDir rend durable un renommage dans dir (sans effet si le système ne le permet pas).
func syncDir(dir string) {
	if d, err := os.Open(dir); err == nil {
		_ = d.Sync()
		_ = d.Close()
	}
}
